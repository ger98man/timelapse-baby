// Загрузка пачками: несколько снимков едут одновременно, а разбирает их
// вызывающий по одному, по порядку.
//
// Зачем это вообще есть. Сборка видео и выгрузка архива — единственные две
// операции, которым нужна вся история сразу, и обе раньше шли строго по
// одному дню: скачали — обработали — скачали следующий. Год превращался в
// 365 последовательных обращений к Google, и большую часть этого времени
// телефон не качал и не считал, а ждал ответа. Задержка складывалась в
// минуты на ровном месте.
//
// Просто запустить всё разом нельзя: год оригиналов — это сотни мегабайт,
// и держать их одновременно телефону нечем. Поэтому середина: качаем по
// LANES штук, а следующую пачку начинаем ровно тогда, когда взялись за
// текущую. Пока вызывающий считает кадр, сеть не простаивает, а в памяти
// живёт самое большее две пачки.

/** Сколько файлов качаем одновременно. */
export const LANES = 4;

/**
 * Идёт по items по порядку, отдавая то, что вернул fetch, — но качает
 * пачками и с опережением на одну.
 *
 * Упавшая загрузка отдаётся как null: один недоступный день не должен
 * ронять годовое видео, а что с ним делать, решает вызывающий.
 *
 * @template T, V
 * @param {T[]} items
 * @param {(item:T, index:number) => Promise<V>} fetch
 * @param {number} lanes сколько качать одновременно
 * @returns {AsyncGenerator<{item:T, index:number, value:V|null}>}
 */
export async function* inLanes(items, fetch, lanes = LANES) {
  const width = Math.max(1, lanes);
  const chunkAt = start => Promise.all(items.slice(start, start + width)
    .map((item, k) => Promise.resolve()
      .then(() => fetch(item, start + k))
      .catch(() => null)));

  let ahead = chunkAt(0);
  for (let c = 0; c < items.length; c += width) {
    const got = await ahead;
    // Следующая пачка уходит в сеть до того, как вызывающий возьмётся за эту.
    ahead = chunkAt(c + width);
    for (let k = 0; k < got.length; k++) {
      yield { item: items[c + k], index: c + k, value: got[k] };
    }
  }
}
